"""Compile the gNMI protocol files into the descriptors the gnmi steps load.

``plugins/steps_gnmi/src/hegemony_steps_gnmi/proto/`` holds ``gnmi.proto``
and ``gnmi_ext.proto`` exactly as openconfig/gnmi publishes them (the tag is
``GNMI_RELEASE`` below). This script compiles them with ``grpcio-tools`` and
writes their serialized ``FileDescriptorProto`` messages to
``_descriptors.py``; the wheel loads those into a private descriptor pool
(``hegemony_steps_gnmi.messages``), so it needs no generated ``_pb2`` code and
no protobuf runtime of one exact version.

Run it after replacing the ``.proto`` files with a new upstream release:

    uv run --with grpcio-tools python scripts/gen_gnmi_descriptors.py

(``ruff``, from the dev dependencies, formats the output.)

``--check`` fails when ``_descriptors.py`` does not match the ``.proto`` files.
"""

from __future__ import annotations

import argparse
import hashlib
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / "plugins" / "steps_gnmi" / "src" / "hegemony_steps_gnmi"
PROTO_DIR = PACKAGE / "proto"
OUTPUT = PACKAGE / "_descriptors.py"

#: The upstream release the .proto files come from.
GNMI_RELEASE = "v0.14.1"
#: Each file's import path, as the upstream files import one another.
IMPORT_PATHS = {
    "gnmi_ext.proto": "github.com/openconfig/gnmi/proto/gnmi_ext/gnmi_ext.proto",
    "gnmi.proto": "github.com/openconfig/gnmi/proto/gnmi/gnmi.proto",
}

HEADER = '''\
# SPDX-FileCopyrightText: 2016 Google Inc.
# SPDX-FileCopyrightText: 2018 Google Inc.
# SPDX-FileCopyrightText: 2026 Rexonix s.r.o.
#
# SPDX-License-Identifier: Apache-2.0

"""Serialized descriptors of openconfig/gnmi {release} (``proto/*.proto``).

Generated by ``scripts/gen_gnmi_descriptors.py``; do not edit. The bytes are
the compiled form of the Apache-2.0 protocol files beside this module.
"""

'''


def compile_descriptors() -> dict[str, bytes]:
    """``{file name: serialized FileDescriptorProto}`` in dependency order."""
    from google.protobuf import descriptor_pb2
    from grpc_tools import protoc  # ty: ignore[unresolved-import]

    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        for name, import_path in IMPORT_PATHS.items():
            target = root / import_path
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(PROTO_DIR / name, target)
        out = root / "set.binpb"
        include = Path(protoc.__file__).parent / "_proto"
        code = protoc.main(
            [
                "protoc",
                f"-I{root}",
                f"-I{include}",
                f"--descriptor_set_out={out}",
                *IMPORT_PATHS.values(),
            ]
        )
        if code != 0:
            raise SystemExit(f"protoc failed with exit code {code}")
        descriptor_set = descriptor_pb2.FileDescriptorSet  # ty: ignore[unresolved-attribute]
        files = descriptor_set.FromString(out.read_bytes()).file
    by_name = {item.name: item.SerializeToString(deterministic=True) for item in files}
    return {name: by_name[path] for name, path in IMPORT_PATHS.items()}


def source_hashes() -> dict[str, str]:
    return {
        name: hashlib.sha256((PROTO_DIR / name).read_bytes()).hexdigest() for name in IMPORT_PATHS
    }


def render(descriptors: dict[str, bytes]) -> str:
    lines = [HEADER.format(release=GNMI_RELEASE)]
    lines.append(f"GNMI_RELEASE = {GNMI_RELEASE!r}\n\n")
    lines.append("#: SHA-256 of each .proto file these descriptors were compiled from.\n")
    lines.append("SOURCE_SHA256 = {\n")
    for name, digest in source_hashes().items():
        lines.append(f"    {name!r}: {digest!r},\n")
    lines.append("}\n\n")
    lines.append("#: Serialized FileDescriptorProto of each file, dependencies first.\n")
    lines.append("FILE_DESCRIPTORS: dict[str, bytes] = {\n")
    for name, data in descriptors.items():
        lines.append(f"    {name!r}: (\n")
        for start in range(0, len(data), 60):
            lines.append(f"        {data[start : start + 60]!r}\n")
        lines.append("    ),\n")
    lines.append("}\n")
    return _formatted("".join(lines))


def _formatted(text: str) -> str:
    """``text`` as ``ruff format`` writes it, so the repository's format check passes."""
    result = subprocess.run(
        [sys.executable, "-m", "ruff", "format", "--stdin-filename", str(OUTPUT), "-"],
        input=text,
        capture_output=True,
        text=True,
        check=False,
        cwd=ROOT,
    )
    if result.returncode != 0:
        raise SystemExit(f"ruff format failed: {result.stderr.strip()}")
    return result.stdout


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="report, do not write")
    args = parser.parse_args(argv)
    text = render(compile_descriptors())
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT.relative_to(ROOT)} is stale; run this script", file=sys.stderr)
            return 1
        print(f"{OUTPUT.relative_to(ROOT)} matches the .proto files")
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
